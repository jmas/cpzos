#!/bin/bash
# Stage 35 — trust the CPZ UI package repository.
#
# The UI is a separate pacman package set. The base image ships only the public
# signing key and the repository configuration; packages are built and signed
# in CI. Stable is enabled; beta is an opt-in include.
set -euo pipefail
cd "$(dirname "$0")/.."
. ./config.sh
. scripts/lib.sh

[ -f "$UI_REPO_KEY" ] || die "missing UI signing key: $UI_REPO_KEY"
[ -n "$UI_REPO_KEY_FPR" ] || die "UI_REPO_KEY_FPR is empty"

log "installing the UI signing key"
KEY_FPR=$(gpg --show-keys --with-colons "$UI_REPO_KEY" | \
    awk -F: '/^fpr:/ { print $10; exit }')
[ -n "$KEY_FPR" ] || die "cannot read a fingerprint from $UI_REPO_KEY"
[ "$KEY_FPR" = "$UI_REPO_KEY_FPR" ] || \
    die "key fingerprint mismatch: file has $KEY_FPR, config has $UI_REPO_KEY_FPR"

install -d "$ROOT/usr/share/pacman/keyrings" "$ROOT/etc/pacman.d"
install -m 0644 "$UI_REPO_KEY" "$ROOT/usr/share/pacman/keyrings/cpz-ui-signing.asc"
in_root "pacman-key --add /usr/share/pacman/keyrings/cpz-ui-signing.asc >/dev/null"
in_root "pacman-key --lsign-key $UI_REPO_KEY_FPR >/dev/null"

log "writing the UI repository configuration"
cat > "$ROOT/etc/pacman.d/cpz-ui.conf" <<EOF
# CPZ UI packages (stable). Generated by scripts/35-ui-repo.sh.
[cpz-ui]
Server = $UI_REPO_STABLE
SigLevel = Required DatabaseRequired
EOF

cat > "$ROOT/etc/pacman.d/cpz-ui-beta.conf" <<EOF
# CPZ UI packages (beta, opt-in). Add this include after cpz-ui.conf.
[cpz-ui-beta]
Server = $UI_REPO_BETA
SigLevel = Required DatabaseRequired
EOF

if ! grep -q '^Include = /etc/pacman.d/cpz-ui.conf$' "$ROOT/etc/pacman.conf"; then
    cat >> "$ROOT/etc/pacman.conf" <<'EOF'

# CPZ UI packages
Include = /etc/pacman.d/cpz-ui.conf
EOF
fi

if [ -n "$UI_APPS_REPO_STABLE" ]; then
    log "writing the app repository configuration"
    cat > "$ROOT/etc/pacman.d/cpz-apps.conf" <<EOF
# CPZ apps (stable). Generated by scripts/35-ui-repo.sh.
[cpz-apps]
Server = $UI_APPS_REPO_STABLE
SigLevel = $UI_APPS_SIGLEVEL
EOF

    if ! grep -q '^Include = /etc/pacman.d/cpz-apps.conf$' "$ROOT/etc/pacman.conf"; then
        cat >> "$ROOT/etc/pacman.conf" <<'EOF'

# CPZ apps
Include = /etc/pacman.d/cpz-apps.conf
EOF
    fi
else
    log "app repository disabled (UI_APPS_REPO_STABLE is empty)"
fi

log "UI repository trusted: $UI_REPO_KEY_FPR"
