#!/usr/bin/env bash
# Rebuild one CPZ stage from the cached previous stage in Docker.
#
# A normal ./build-docker.sh run starts at stage0 (debootstrap). During
# development most changes are in stage2/stage3; this helper keeps the work
# volume and rebuilds only the requested stage and the stages after it. The
# previous stage rootfs is copied fresh, so the result is the same as a full
# build with the same package archive state.
#
# Usage:
#   tools/build-fast.sh [stage0|stage1|stage2|stage3]
#
# The default is stage3. Run a full ./build-docker.sh with
# PIGEN_DOCKER_OPTS="--volume <volume>:/pi-gen/work" (or
# ./tools/build-fast.sh stage0) once first so the previous stage exists.
#
# Environment:
#   CPZ_WORK_VOLUME   Docker volume mounted at /pi-gen/work
#                     (default: cpz-pigen-work)
#   FAST_COMPRESSION  DEPLOY_COMPRESSION for the fast build (default: gz;
#                     use xz for a release-shaped archive, none for raw .img)
#   CPZ_CONFIG        build config (default: <repo>/config)
#   DOCKER            docker command, e.g. "sudo docker" (default: docker)
set -euo pipefail

root=$(CDPATH='' cd -- "$(dirname -- "$0")/.." && pwd)
cd "$root"

usage() {
	cat <<'EOF'
Rebuild one CPZ stage from the cached previous stage (Docker).

Usage: tools/build-fast.sh [stage0|stage1|stage2|stage3]

Options:
  --help, -h      show this help

Environment:
  CPZ_WORK_VOLUME  Docker volume mounted at /pi-gen/work
                   (default: cpz-pigen-work)
  FAST_COMPRESSION DEPLOY_COMPRESSION for the fast build
                   (default: gz; xz or none are also useful)
  CPZ_CONFIG       build config (default: <repo>/config)
  DOCKER           docker command, e.g. "sudo docker"
EOF
}

die() {
	printf 'build-fast: %s\n' "$*" >&2
	exit 1
}

stage="stage3"
case "${1:-}" in
	'') ;;
	-h | --help)
		usage
		exit 0
		;;
	stage0 | stage1 | stage2 | stage3) stage=$1 ;;
	0 | 1 | 2 | 3) stage="stage$1" ;;
	*) die "unknown stage '$1' (expected stage0..stage3)" ;;
esac
[ "$#" -le 1 ] || die "unexpected arguments"

config=${CPZ_CONFIG:-"$root/config"}
[ -f "$config" ] || die "config not found: $config (cp config.cpz.example config)"
# shellcheck source=/dev/null
. "$config"
[ -n "${IMG_NAME:-}" ] || die "IMG_NAME not set in $config"

docker=${DOCKER:-docker}
volume=${CPZ_WORK_VOLUME:-cpz-pigen-work}
compression=${FAST_COMPRESSION:-gz}
case "$compression" in
	xz | gz | zip | none) ;;
	*) die "FAST_COMPRESSION must be xz, gz, zip or none (got '$compression')" ;;
esac

work_container="${WORK_DIR:-/pi-gen/work/${IMG_NAME}}"
case "$work_container" in
	/pi-gen/work/*) ;;
	*) die "fast builds require WORK_DIR under /pi-gen/work (got '$work_container')" ;;
esac
work_rel=${work_container#/pi-gen/work/}
case "$work_rel" in
	'' | *..* | /*) die "invalid WORK_DIR '$work_container'" ;;
esac

case "$stage" in
	stage0)
		prev=""
		stages="stage0 stage1 stage2 stage3"
		remove="stage0 stage1 stage2 stage3"
		;;
	stage1)
		prev="stage0"
		stages="stage1 stage2 stage3"
		remove="stage1 stage2 stage3"
		;;
	stage2)
		prev="stage1"
		stages="stage2 stage3"
		remove="stage2 stage3"
		;;
	stage3)
		prev="stage2"
		stages="stage3"
		remove="stage3"
		;;
esac

run_docker() {
	# shellcheck disable=SC2086  # DOCKER may be "sudo docker"
	$docker "$@"
}

run_docker ps >/dev/null 2>&1 || {
	case "$docker" in
		sudo\ *) ;;
		*) docker="sudo $docker" ;;
	esac
	run_docker ps >/dev/null 2>&1 ||
		die "cannot connect to Docker; start Docker Desktop or use ./build-docker.sh"
}

if [ -n "${PIGEN_DOCKER_OPTS:-}" ] &&
	printf '%s\n' "$PIGEN_DOCKER_OPTS" | grep -q '/pi-gen/work'; then
	die "PIGEN_DOCKER_OPTS already mounts /pi-gen/work; set CPZ_WORK_VOLUME instead"
fi

run_docker volume create "$volume" >/dev/null

stage_list=""
for name in $stages; do
	stage_list="${stage_list}${stage_list:+ }/pi-gen/$name"
done

tmp_cfg=$(mktemp "$root/.build-fast.XXXXXX")
trap 'rm -f "$tmp_cfg"' EXIT
cp "$config" "$tmp_cfg"
{
	printf '\n# generated by tools/build-fast.sh\n'
	printf 'CLEAN=0\n'
	printf 'STAGE_LIST="%s"\n' "$stage_list"
	printf 'DEPLOY_COMPRESSION=%s\n' "$compression"
	if [ -n "$prev" ]; then
		printf 'PREV_ROOTFS_DIR="%s/%s/rootfs"\n' "$work_container" "$prev"
	else
		printf 'PREV_ROOTFS_DIR=\n'
	fi
} >>"$tmp_cfg"

printf 'build-fast: %s after %s, work=%s, compression=%s\n' \
	"$stage" "${prev:-clean bootstrap}" "$volume" "$compression"

# Remove only the stages that are about to be rebuilt. The previous stage
# remains untouched and is used as the clean copy source.
# shellcheck disable=SC2016,SC2086  # helper vars expand in the container; remove is a list
run_docker run --rm -v "${volume}:/w" debian:trixie sh -eu -c '
	work=$1
	prev=$2
	shift 2
	if [ -n "$prev" ] && [ ! -d "/w/$work/$prev/rootfs" ]; then
		echo "missing cached /w/$work/$prev/rootfs" >&2
		echo "run a full build into the same Docker work volume first" >&2
		echo "(see the Fast local iterations section in README.md)" >&2
		exit 1
	fi
	for name in "$@"; do
		rm -rf "/w/$work/$name/rootfs"
	done
' sh "$work_rel" "$prev" $remove

PIGEN_DOCKER_OPTS="${PIGEN_DOCKER_OPTS:-} --volume ${volume}:/pi-gen/work" \
	"$root/build-docker.sh" -c "$tmp_cfg"
